// 范例模块 encoder83_ref：参考答案（供对照学习），原模块 encoder83 请自行完成
// 题目：编码器——输入 in[8:3] 共 6 根线，哪根为 1 就在 out 低 3 位输出其编号-3，
//       out[3] 作为"有有效输入"指示位（全 0 时 out=0000）
// 思路：if-else 链或 case 逐一判断，多线同时为 1 时低位优先
// 关键点：组合逻辑所有分支赋值完整，避免锁存器
//=====================================================
module encoder83_ref(
    input  [8:3] in,
    output reg [3:0] out
);
    always @(*) begin
        case (in)
            6'b000001: out = 4'b0000;   // in[3] 有效 -> 编号 0
            6'b000010: out = 4'b0001;   // in[4] 有效 -> 编号 1
            6'b000100: out = 4'b0010;   // in[5] 有效 -> 编号 2
            6'b001000: out = 4'b0011;   // in[6] 有效 -> 编号 3
            6'b010000: out = 4'b0100;   // in[7] 有效 -> 编号 4
            6'b100000: out = 4'b0101;   // in[8] 有效 -> 编号 5
            default:   out = 4'b0000;   // 全 0 或多线同时有效：输出 0
        endcase
    end
endmodule